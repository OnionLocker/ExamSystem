#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BATCHES = path.join(ROOT, 'batches');
const OUTPUT = path.join(ROOT, 'src/practice/readSpotArchivedPacks.js');
const SIDECAR = 'read-spot-packs.json';
const FIELD_RE = /\[\[([a-zA-Z0-9_-]+)\|([^\]]+)\]\]/g;

const asciiJson = (value) =>
  JSON.stringify(value, null, 2).replace(
    /[^\p{ASCII}]/gu,
    (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`,
  );

const validatePack = (pack, batchId) => {
  if (!pack.id || !pack.theme || pack.sourceBatch !== batchId) {
    throw new Error(`${batchId}: invalid pack identity`);
  }
  if (!Array.isArray(pack.paragraphs) || pack.paragraphs.length < 4 || pack.paragraphs.length > 5) {
    throw new Error(`${pack.id}: expected 4-5 paragraphs`);
  }
  const marked = pack.paragraphs.join('\n');
  const fields = new Set([...marked.matchAll(FIELD_RE)].map((match) => match[1]));
  const displayed = marked.replace(FIELD_RE, '$2').replace(/\s/g, '');
  if (displayed.length < 580 || (displayed.match(/\d+(?:\.\d+)?/g) || []).length < 20) {
    throw new Error(`${pack.id}: material is too short or sparse`);
  }
  for (const kind of ['basic', 'advanced']) {
    if (!Array.isArray(pack[kind]) || pack[kind].length === 0) {
      throw new Error(`${pack.id}: missing ${kind} questions`);
    }
    for (const question of pack[kind]) {
      for (const key of question.keys || []) {
        if (!fields.has(key) || !pack.labels?.[key]) {
          throw new Error(`${pack.id}/${kind}: unresolved field ${key}`);
        }
      }
    }
  }
};

const batchDirs = fs.readdirSync(BATCHES, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => path.join(BATCHES, entry.name))
  .filter((dir) => fs.existsSync(path.join(dir, SIDECAR)))
  .sort();

const packs = [];
for (const dir of batchDirs) {
  const gate = spawnSync(
    'python3',
    [path.join(ROOT, 'scripts/generation_gate.py'), 'verify', dir],
    { cwd: ROOT, encoding: 'utf8' },
  );
  if (gate.status !== 0) {
    throw new Error(`Refusing unsigned batch ${path.basename(dir)}: ${gate.stdout || gate.stderr}`);
  }
  const items = JSON.parse(fs.readFileSync(path.join(dir, SIDECAR), 'utf8'));
  if (!Array.isArray(items) || items.length === 0) {
    throw new Error(`${path.join(dir, SIDECAR)} must contain a non-empty array`);
  }
  for (const pack of items) validatePack(pack, path.basename(dir));
  packs.push(...items);
}

const ids = packs.map((pack) => pack.id);
if (ids.some((id) => !id) || new Set(ids).size !== ids.length) {
  throw new Error('Archived read-spot pack ids must be present and unique');
}

const source = [
  '// Generated by scripts/sync-ziliao-read-spot.mjs from quality-gated batches.',
  '// Do not edit this file directly.',
  '',
  `export const ARCHIVED_READ_SPOT_PACKS = ${asciiJson(packs)};`,
  '',
].join('\n');
fs.writeFileSync(OUTPUT, source, 'ascii');
console.log(`synced ${packs.length} archived read-spot packs from ${batchDirs.length} batch(es)`);
